import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const shell = readFileSync(root + 'shared/checkout-shell.html', 'utf8');
const outputs = new Map([
  ['react-native/src/shell.ts', '// Generated by mobile/scripts/generate-shell.mjs; edit shared/checkout-shell.html.\nexport const SHELL = ' + JSON.stringify(shell) + ';\n'],
  ['swift/Sources/RecurrenteCheckout/Shell.swift', '// Generated; edit mobile/shared/checkout-shell.html.\nimport Foundation\nenum CheckoutShell {\n    static let html = #"""\n' + shell.trimEnd() + '\n"""#\n}\n'],
  ['kotlin/src/main/java/com/recurrente/checkout/CheckoutShell.kt', '// Generated; edit mobile/shared/checkout-shell.html.\npackage com.recurrente.checkout\ninternal object CheckoutShell {\n    val html = """\n' + shell.replaceAll('$', "${'$'}").trimEnd() + '\n""".trimIndent()\n}\n'],
]);
for (const [path, text] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(root + path, 'utf8') !== text) throw new Error('Stale generated file: ' + path);
  } else writeFileSync(root + path, text);
}
// Explicit export for the separate, existing Flutter repository.
const flag = process.argv.indexOf('--flutter');
if (flag !== -1) writeFileSync(process.argv[flag + 1], '// Generated from recurrente-checkout/mobile/shared/checkout-shell.html.\n/// Canonical embedded frame bridge, generated from recurrente-checkout.\nconst checkoutShell = r\'\'\'\n' + shell + "''';\n");
